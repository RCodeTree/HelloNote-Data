USE hello_note;

-- 1.1 给 users 增加 bio 列（列已存在则跳过；可反复执行）
--     用 DATABASE() 而非硬编码库名，切换 schema 后仍安全。
DROP PROCEDURE IF EXISTS sp_v4_add_users_bio;

DELIMITER $$
CREATE PROCEDURE sp_v4_add_users_bio()
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE()
          AND TABLE_NAME = 'users'
          AND COLUMN_NAME = 'bio'
    ) THEN
        ALTER TABLE users
            ADD COLUMN bio VARCHAR(500) NULL COMMENT '个人简介';
    END IF;
END$$
DELIMITER ;

CALL sp_v4_add_users_bio();

DROP PROCEDURE IF EXISTS sp_v4_add_users_bio;


